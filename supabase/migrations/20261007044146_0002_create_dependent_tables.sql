-- Create Operating Theater Table
CREATE TABLE OPERATING_THEATER (
    OT_ID SERIAL PRIMARY KEY,
    Branch_ID INT REFERENCES HOSPITAL_BRANCH(Branch_ID) ON DELETE CASCADE,
    Room_Number VARCHAR(50) NOT NULL,
    OT_Specialty VARCHAR(100)
);

-- Create Surgical Asset Table
CREATE TABLE SURGICAL_ASSET (
    Asset_ID SERIAL PRIMARY KEY,
    Current_Branch_ID INT REFERENCES HOSPITAL_BRANCH(Branch_ID) ON DELETE SET NULL,
    Asset_Name VARCHAR(150) NOT NULL,
    Sterilization_Status VARCHAR(50) DEFAULT 'Ready'
);

-- Create Surgery Booking Table
CREATE TABLE SURGERY_BOOKING (
    Booking_ID SERIAL PRIMARY KEY,
    Patient_ID INT REFERENCES PATIENT(Patient_ID) ON DELETE CASCADE,
    OT_ID INT REFERENCES OPERATING_THEATER(OT_ID) ON DELETE RESTRICT,
    Scheduled_Start TIMESTAMP NOT NULL,
    Booking_Status VARCHAR(50) DEFAULT 'Scheduled'
);